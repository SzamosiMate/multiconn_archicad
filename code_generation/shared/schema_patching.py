from copy import deepcopy
from typing import Any, Optional


def _get_target_from_path(
    defs: dict[str, Any], parent_name: str, path: list[str]
) -> tuple[Optional[dict], Optional[dict], str]:
    """
    Navigates the schema dict. Returns (parent_of_target, target_schema, last_key_used).
    Automatically assumes segments are properties unless the segment is 'items'.
    """
    if parent_name not in defs:
        return None, None, ""

    current = defs[parent_name]

    # We need to keep track of the container to perform the $ref swap at the end
    parent_of_target = None
    last_key = ""

    for segment in path:
        parent_of_target = current
        last_key = segment

        if segment == "items":
            current = current.get("items")
        else:
            # Assume it is a property
            current = current.get("properties", {}).get(segment)

        if not isinstance(current, dict):
            return None, None, ""

    return parent_of_target, current, last_key


def _require_target(defs: dict[str, Any], parent_name: str, path: list[str]) -> tuple[Optional[dict], dict, str]:
    """
    Validates a patch target before patching. The patch calls are hand-maintained,
    so a missing parent or path means the upstream schema changed (e.g. a command
    was renamed) - fail loudly instead of silently skipping the patch and letting
    model names regress to autogenerated ones (LayoutsDatum instead of LayoutData).
    An existing reference also requires review: an upstream fix may have made the
    patch redundant, or changed the referenced definition.
    """
    if parent_name not in defs:
        raise KeyError(
            f"Schema patch target '{parent_name}' not found in the master schema. "
            f"The upstream command was probably renamed - update the patch in schema_patching.py."
        )

    container, target_schema, key = _get_target_from_path(defs, parent_name, path)
    if target_schema is None:
        raise KeyError(
            f"Schema patch path {path} does not resolve under '{parent_name}'. "
            f"The upstream schema probably changed - update the patch in schema_patching.py."
        )
    if "$ref" in target_schema:
        raise ValueError(
            f"Schema patch target '{parent_name}' / {path} already references {target_schema['$ref']!r}. "
            f"Review the upstream definition before updating or removing the patch in schema_patching.py."
        )
    return container, target_schema, key


def _require_new_definition(defs: dict[str, Any], name: str) -> None:
    if name in defs:
        raise ValueError(
            f"Schema patch definition '{name}' already exists. "
            "Review the upstream definition before updating or removing the patch in schema_patching.py."
        )


def extract_inline_schema(defs: dict[str, Any], parent_name: str, path: list[str], new_def_name: str):
    """
    Helper to extract an inline schema definition into a named $ref.
    Path is simplified: ['surveyPoint', 'position'] instead of ['properties', 'surveyPoint', 'properties', 'position']
    """
    container, target_schema, key = _require_target(defs, parent_name, path)
    _require_new_definition(defs, new_def_name)

    print(f"  -> Extracting Model {parent_name} / {path} to {new_def_name}")

    # 1. Store the target in top-level defs
    defs[new_def_name] = target_schema

    # 2. Replace the original location with a $ref
    if container:
        if key == "items":
            container["items"] = {"$ref": f"#/$defs/{new_def_name}"}
        else:
            container["properties"][key] = {"$ref": f"#/$defs/{new_def_name}"}


def extract_inline_enum(defs: dict[str, Any], parent_name: str, path: list[str], new_def_name: str):
    """
    Helper to extract an inline enum definition into a named $ref.
    """
    container, target_schema, key = _require_target(defs, parent_name, path)

    if "enum" not in target_schema:
        raise ValueError(f"Expected enum at '{parent_name}' / {path}, but found none. Review the upstream definition.")
    _require_new_definition(defs, new_def_name)

    print(f"  -> Extracting Enum {parent_name} / {path} to {new_def_name}")

    defs[new_def_name] = target_schema
    if container:
        if key == "items":
            container["items"] = {"$ref": f"#/$defs/{new_def_name}"}
        else:
            container["properties"][key] = {"$ref": f"#/$defs/{new_def_name}"}


def replace_inline_schema_with_ref(
    defs: dict[str, Any], parent_name: str, path: list[str], ref_name: str, preserve_description: bool = False
):
    """
    Replaces an inline schema at the given path with a $ref.
    Optionally preserves the original 'description' as a sibling keyword (valid in Draft 2019-09).
    """
    container, target_schema, key = _require_target(defs, parent_name, path)

    print(f"  -> Replacing inline Model {parent_name} / {path} with {ref_name}")

    new_schema = {"$ref": f"#/$defs/{ref_name}"}

    if preserve_description and "description" in target_schema:
        new_schema["description"] = target_schema["description"]

    if container:
        if key == "items":
            container["items"] = new_schema
        else:
            container["properties"][key] = new_schema


def name_required_variants(defs: dict[str, Any], parent_name: str, path: list[str], variant_names: list[str]):
    """Name conditional required-field variants so generators do not invent numeric suffixes."""
    _, target_schema, _ = _require_target(defs, parent_name, path)
    union_keys = [key for key in ("oneOf", "anyOf") if key in target_schema]
    if len(union_keys) != 1:
        raise ValueError(f"Expected exactly one conditional union at '{parent_name}' / {path}, found {union_keys}.")

    union_key = union_keys[0]
    variants = target_schema[union_key]
    if not isinstance(variants, list) or len(variants) != len(variant_names):
        raise ValueError(
            f"Expected {len(variant_names)} variants at '{parent_name}' / {path}, found "
            f"{len(variants) if isinstance(variants, list) else type(variants).__name__}."
        )

    for variant_name in variant_names:
        _require_new_definition(defs, variant_name)

    common_schema = {key: deepcopy(value) for key, value in target_schema.items() if key != union_key}
    common_required = common_schema.pop("required", [])
    for variant, variant_name in zip(variants, variant_names):
        if not isinstance(variant, dict) or set(variant) != {"required"} or not isinstance(variant["required"], list):
            raise ValueError(f"Expected a required-only variant at '{parent_name}' / {path}, found {variant!r}.")
        named_variant = deepcopy(common_schema)
        named_variant["required"] = list(dict.fromkeys([*common_required, *variant["required"]]))
        defs[variant_name] = named_variant

    target_schema.clear()
    target_schema[union_key] = [{"$ref": f"#/$defs/{name}"} for name in variant_names]


def extract_union_variant(defs: dict[str, Any], parent_name: str, path: list[str], index: int, new_def_name: str):
    """Name an inline oneOf/anyOf branch, rejecting stale or already named targets."""
    _, target_schema, _ = _require_target(defs, parent_name, path)
    union_keys = [key for key in ("oneOf", "anyOf") if key in target_schema]
    if len(union_keys) != 1:
        raise ValueError(f"Expected exactly one union at '{parent_name}' / {path}, found {union_keys}.")
    variants = target_schema[union_keys[0]]
    if not isinstance(variants, list) or not 0 <= index < len(variants) or not isinstance(variants[index], dict):
        raise ValueError(f"Missing union variant {index} at '{parent_name}' / {path}.")
    branch = variants[index]
    if "$ref" in branch:
        raise ValueError(
            f"Schema patch union variant {index} at '{parent_name}' / {path} already references {branch['$ref']!r}. "
            "Review the upstream definition before updating or removing the patch in schema_patching.py."
        )
    _require_new_definition(defs, new_def_name)
    defs[new_def_name] = branch
    variants[index] = {"$ref": f"#/$defs/{new_def_name}"}


